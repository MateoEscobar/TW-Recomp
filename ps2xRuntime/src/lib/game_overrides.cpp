// Per-game override registry: descriptors registered with PS2_REGISTER_GAME_OVERRIDE are applied by
// PS2Runtime::loadELF() when the ELF name / entry / CRC32 match (see game_overrides.h).
//
// [TWR-27] This repo is The Warriors (SLUS_212.15) only. The ~8 000 lines of overrides this file used
// to carry were inherited from BT3-Recomp and hooked BT3 ELF addresses (88 of 92 are not function
// starts in Warriors, the other 4 replaced real Warriors functions with BT3 logic); they were removed
// together with the compat code of two other games. Every address an override hooks must be a verified
// Warriors function start (a ps2xRuntime/src/runner/*_0x<addr>.cpp must exist):
// tools/check_override_addresses.py enforces it in CI. Never ret0/ret1 or stub a game function to
// get the boot past a wait -- fix the producer in the runtime or the IOP (docs/boot.md).
// Symbols other runtime files used from the old layer live in ps2_frame_state.cpp, ps2_simsnap.cpp
// and ps2_bt3_inert.cpp.
