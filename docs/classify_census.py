#!/usr/bin/env python3
"""
classify_census.py — TWR-23 / warriors fps60_sites.txt generator

Usage:
    python3 classify_census.py census_out.csv > fps60_sites_candidates.txt

    Reads the CSV written by PS2X_STEPCENSUS and outputs candidate sites
    in fps60_sites.txt format (0xPC kind).  Review the output, remove false
    positives, and write the result to games/warriors/fps60_sites.txt.

CSV columns (from ps2_stepcensus.cpp):
    pc, count, frames, per_frame, size, addr_lo, addr_hi,
    chain_pct, same_pct, fplaus_pct, fdelta, fdelta_pct,
    idelta, idelta_pct, ra
"""
import csv
import sys

def classify(row):
    """
    Returns (kind, reason) where kind is 'f','h','d','i','j', or None.
    """
    pc        = int(row['pc'], 16)
    count     = int(row['count'])
    frames    = int(row['frames'])
    per_frame = float(row['per_frame'])
    size      = int(row['size'])
    chain_pct = float(row['chain_pct'])
    same_pct  = float(row['same_pct'])
    fplaus    = float(row['fplaus_pct'])
    fdelta    = float(row['fdelta'])
    fdelta_pct = float(row['fdelta_pct'])
    idelta    = int(row['idelta'])
    idelta_pct = float(row['idelta_pct'])
    ra        = int(row['ra'], 16) if row['ra'] else 0
    is_vec    = bool(size & 16)

    # Minimum sample quality: need enough frames to be confident
    if frames < 10:
        return None, "too few frames"
    # Constant value (same_pct > 90%) — not a per-frame accumulator
    if same_pct > 90:
        return None, "mostly constant"
    # Vector library helpers (0x120000..0x122400) share their PC across many
    # callers — skip them in the flat table; they appear as vector sites with ra.
    if not is_vec and 0x120000 <= pc < 0x122400:
        return None, "vector helper (shared pc)"
    # Sites that fire many times per frame are loop bodies (matrix math, etc.)
    # not frame-level counters.
    if per_frame > 4.0:
        return None, "loop body (per_frame > 4)"
    # Sites that almost never fire per frame are event-driven, not timing.
    if per_frame < 0.3:
        return None, "event-driven (per_frame < 0.3)"

    # --- Vector store (sqc2 / size=16) ---
    if is_vec:
        if fplaus >= 60 and chain_pct >= 30 and fdelta_pct >= 35 and ra:
            return ('f', ra), f"vector float acc (chain={chain_pct:.0f}% fplaus={fplaus:.0f}% fdelta_pct={fdelta_pct:.0f}%)"
        return None, "vector but not classified"

    # --- Scalar stores ---
    if size == 4:
        if fplaus >= 55:
            # Float accumulator: accumulates over frames with consistent delta
            if chain_pct >= 30 and fdelta_pct >= 35 and 0.3 <= per_frame <= 3.5:
                return 'f', f"float acc (chain={chain_pct:.0f}% fplaus={fplaus:.0f}% fdelta_pct={fdelta_pct:.0f}%)"
            # Rate assignment: sets a rate value (not cumulative)
            if chain_pct < 25 and same_pct < 75 and 0.3 <= per_frame <= 2.5:
                return 'h', f"rate assign (chain={chain_pct:.0f}% fplaus={fplaus:.0f}%)"
    if size in (1, 2, 4) and fplaus < 45:
        # Countdown timer: decrements each frame
        if idelta < 0 and idelta_pct >= 45 and 0.3 <= per_frame <= 2.5:
            return 'd', f"countdown (idelta={idelta} idelta_pct={idelta_pct:.0f}%)"
        # Integer counter: increments by 1
        if idelta == 1 and idelta_pct >= 45 and chain_pct >= 25 and 0.3 <= per_frame <= 2.5:
            return 'i', f"int counter (chain={chain_pct:.0f}% idelta_pct={idelta_pct:.0f}%)"
        # Integer accumulator with large step (ki drain)
        if abs(idelta) >= 2 and chain_pct >= 35 and idelta_pct >= 45 and 0.3 <= per_frame <= 3.5:
            return 'j', f"int acc large step (idelta={idelta} chain={chain_pct:.0f}%)"

    return None, "unclassified"


def main():
    if len(sys.argv) < 2:
        print("Usage: classify_census.py <census_out.csv>", file=sys.stderr)
        sys.exit(1)

    sites = []   # (pc, kind, ra, reason, row)
    unclassified = []

    with open(sys.argv[1], newline='') as f:
        reader = csv.DictReader(f)
        for row in reader:
            result, reason = classify(row)
            pc = int(row['pc'], 16)
            if result is None:
                unclassified.append((pc, reason, row))
            else:
                ra = None
                if isinstance(result, tuple):
                    kind, ra = result
                else:
                    kind = result
                sites.append((pc, kind, ra, reason, row))

    # Sort by PC
    sites.sort(key=lambda x: x[0])

    print("# warriors fps60_sites.txt candidates")
    print("# Generated by classify_census.py — review before committing")
    print("# Format: 0xPC kind [# comment]")
    print("#")
    print("# Kinds: f=float acc, h=rate assign, d=countdown, i=int counter,")
    print("#        j=int acc large step, D=duration (paired with d)")
    print(f"# Total candidates: {len(sites)}")
    print()

    last_kind = None
    for pc, kind, ra, reason, row in sites:
        if kind != last_kind:
            print(f"\n# --- {kind} sites ---")
            last_kind = kind
        per_frame = float(row['per_frame'])
        if ra is not None:
            print(f"0x{pc:06x}:0x{ra:06x} {kind}  # {reason}  pf={per_frame:.2f}")
        else:
            print(f"0x{pc:06x} {kind}  # {reason}  pf={per_frame:.2f}")

    if unclassified:
        print(f"\n# --- Unclassified ({len(unclassified)} sites, not written) ---")
        for pc, reason, row in sorted(unclassified, key=lambda x: x[0])[:30]:
            pf = float(row['per_frame'])
            fp = float(row['fplaus_pct'])
            ch = float(row['chain_pct'])
            id_ = int(row['idelta'])
            idp = float(row['idelta_pct'])
            sz = int(row['size'])
            print(f"# 0x{pc:06x} {reason} [pf={pf:.2f} sz={sz} fplaus={fp:.0f}% chain={ch:.0f}% idelta={id_} idelta_pct={idp:.0f}%]")

    print(f"\n# Stats: {len(sites)} classified, {len(unclassified)} unclassified", file=sys.stderr)

if __name__ == '__main__':
    main()
